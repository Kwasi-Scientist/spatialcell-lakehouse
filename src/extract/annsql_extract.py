# Define function to filter dataset for marker genes
def filter_marker_dict(marker_dict, adata):
    """
    Keep only marker genes that are present in adata.var_names.

    Parameters
    ----------
    marker_dict : dict
        Dictionary mapping cell type names to marker gene lists.
    adata : anndata.AnnData
        AnnData object containing gene names in adata.var_names.

    Returns
    -------
    dict
        Dictionary with the same keys, but only available genes retained.
        Cell types with zero available markers are removed.
    """
    var_names = set(adata.var_names)

    return {
        cell_type: [gene for gene in marker_genes if gene in var_names]
        for cell_type, marker_genes in marker_dict.items()
        if any(gene in var_names for gene in marker_genes)
    }

