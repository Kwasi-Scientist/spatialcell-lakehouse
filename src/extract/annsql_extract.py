# Define function to flatten avialble marker gene dict
def flatten_marker_dict(marker_dict):
    """
    Flatten a marker dictionary into a sorted unique gene list.

    Parameters
    ----------
    marker_dict : dict
        Dictionary mapping cell type names to marker gene lists.

    Returns
    -------
    list
        Sorted unique marker genes.
    """
    return sorted({
        gene
        for marker_genes in marker_dict.values()
        for gene in marker_genes
    })

# Define function to find available marker genes
def get_available_marker_genes(marker_dict, adata):
    """
    Return available and missing marker genes for an AnnData object.
    """
    requested_genes = flatten_marker_dict(marker_dict)
    adata_genes = set(adata.var_names)

    available_genes = [
        gene for gene in requested_genes
        if gene in adata_genes
    ]

    missing_genes = sorted(set(requested_genes) - adata_genes)

    return available_genes, missing_genes

